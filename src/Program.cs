    class IniFile
    {
        [DllImport("kernel32.dll", CharSet = CharSet.Unicode)]
        static extern int GetPrivateProfileString(string section, string key, string def, char[] ret, int size, string path);
        [DllImport("kernel32.dll", CharSet = CharSet.Unicode)]
        static extern bool WritePrivateProfileString(string section, string key, string value, string path);

        public readonly string Path;
        public IniFile(string path)
        {
            Path = path;
            // A UTF-16 file keeps folder names with any characters intact.
            try { if (!File.Exists(path)) File.WriteAllText(path, "", Encoding.Unicode); } catch { }
        }

        public string Read(string section, string key, string def)
        {
            var buf = new char[32768];
            int n = GetPrivateProfileString(section, key, def, buf, buf.Length, Path);
            return new string(buf, 0, n);
        }

        public void Write(string section, string key, string value) { WritePrivateProfileString(section, key, value, Path); }

        public List<string> Keys(string section)
        {
            var buf = new char[65536];
            int n = GetPrivateProfileString(section, null, "", buf, buf.Length, Path);
            return new string(buf, 0, n).Split(new[] { '\0' }, StringSplitOptions.RemoveEmptyEntries).ToList();
        }
    }

    class Settings
    {
        public readonly IniFile Ini = new IniFile(System.IO.Path.Combine(AppDomain.CurrentDomain.BaseDirectory, "ROM-Check-O-MATIC.ini"));
        const string S = "Settings";

        // ---- Collections (No-Intro, Redump...). Each has its own folders, filters and hand-picked DATs.
        // The first one, No-Intro, keeps its settings in [Settings] as before; others get [Collection: Name].
        public const string DefaultCollection = "No-Intro";
        string collectionOverride;
        public Settings() { }
        public Settings(string collection) { collectionOverride = collection; }   // for the command line

        public List<string> Collections
        {
            get
            {
                var list = Ini.Read(S, "Collections", DefaultCollection + ", Redump").Split(',').Select(x => x.Trim()).Where(x => x.Length > 0).ToList();
                if (!list.Contains(DefaultCollection)) list.Insert(0, DefaultCollection);
                return list;
            }
            set { Ini.Write(S, "Collections", string.Join(", ", value)); }
        }
        public string Collection
        {
            get { string c = collectionOverride ?? Ini.Read(S, "Collection", DefaultCollection); return Collections.Contains(c) ? c : DefaultCollection; }
            set { Ini.Write(S, "Collection", value); }
        }
        bool IsDefault { get { return Collection == DefaultCollection; } }
        string C { get { return IsDefault ? S : "Collection: " + Collection; } }
        string MapSection { get { return IsDefault ? "DatMap" : "DatMap: " + Collection; } }

        // ---- Per collection
        public string RomFolder { get { return Ini.Read(C, "RomFolder", ""); } set { Ini.Write(C, "RomFolder", value); } }
        public string DatFolder
        {
            get { return Ini.Read(C, "DatFolder", IsDefault ? AppDomain.CurrentDomain.BaseDirectory.TrimEnd('\\') : ""); }
            set { Ini.Write(C, "DatFolder", value); }
        }
        public string IncomingFolder { get { return Ini.Read(C, "AddFromFolder", ""); } set { Ini.Write(C, "AddFromFolder", value); } }
        public string CueFolder { get { return Ini.Read(C, "CueFolder", ""); } set { Ini.Write(C, "CueFolder", value); } }
        public bool AutoAdd { get { return Ini.Read(C, "AutoAdd", "0") == "1"; } set { Ini.Write(C, "AutoAdd", value ? "1" : "0"); } }
        // TOSEC packs (one zip per DAT): fix games inside them (on), or unpack them into one zip per game (off).
        public bool KeepPacks { get { return Ini.Read(C, "KeepPacks", "1") != "0"; } set { Ini.Write(C, "KeepPacks", value ? "1" : "0"); } }
        public bool OneGamePerTitle { get { return Ini.Read(C, "OneGamePerTitle", "0") == "1"; } set { Ini.Write(C, "OneGamePerTitle", value ? "1" : "0"); } }
        public string Regions { get { return Ini.Read(C, "RegionOrder", Preference.DefaultRegions); } set { Ini.Write(C, "RegionOrder", value); } }
        public string IgnoredPack { get { return Ini.Read(C, "IgnoredPack", ""); } set { Ini.Write(C, "IgnoredPack", value); } }

        // Kinds of game to leave out, e.g. "Beta,Proto". Older settings only had KeepAftermarket.
        public GameType Exclude
        {
            get
            {
                string v = Ini.Read(C, "LeaveOut", null);
                if (v != null && Ini.Keys(C).Contains("LeaveOut")) return GameTypes.Parse(v);
                return IsDefault && Ini.Read(S, "KeepAftermarket", "1") == "0" ? GameType.Aftermarket : GameType.None;
            }
            set { Ini.Write(C, "LeaveOut", GameTypes.ToList(value)); if (IsDefault) Ini.Write(S, "KeepAftermarket", null); }
        }

        // Regions whose games are left out, e.g. "Brazil, Korea".
        public string IgnoredRegions { get { return Ini.Read(C, "IgnoredRegions", ""); } set { Ini.Write(C, "IgnoredRegions", value); } }

        // ---- Shared by all collections
        public bool ShowMia { get { return Ini.Read(S, "ShowMIA", "1") == "1"; } set { Ini.Write(S, "ShowMIA", value ? "1" : "0"); } }
        public string Window { get { return Ini.Read(S, "Window", ""); } set { Ini.Write(S, "Window", value); } }
        public string Theme { get { return Ini.Read(S, "Theme", "System"); } set { Ini.Write(S, "Theme", value); } }
        public bool ShowTips { get { return Ini.Read(S, "ShowTips", "1") != "0"; } set { Ini.Write(S, "ShowTips", value ? "1" : "0"); } }
        public bool UseRecycleBin { get { return Ini.Read(S, "RecycleBin", "1") != "0"; } set { Ini.Write(S, "RecycleBin", value ? "1" : "0"); } }
        public bool CheckUpdates { get { return Ini.Read(S, "CheckUpdates", "0") == "1"; } set { Ini.Write(S, "CheckUpdates", value ? "1" : "0"); } }
        public string MentionedUpdate { get { return Ini.Read(S, "MentionedUpdate", ""); } set { Ini.Write(S, "MentionedUpdate", value); } }
        public bool RemoveDownloads { get { return Ini.Read(S, "RemoveDownloads", "1") == "1"; } set { Ini.Write(S, "RemoveDownloads", value ? "1" : "0"); } }
        public bool ScanOnOpen { get { return Ini.Read(S, "ScanOnOpen", "1") == "1"; } set { Ini.Write(S, "ScanOnOpen", value ? "1" : "0"); } }
        public bool AutoFitColumns { get { return Ini.Read(S, "AutoFitColumns", "1") != "0"; } set { Ini.Write(S, "AutoFitColumns", value ? "1" : "0"); } }
        public bool KeepAwake { get { return Ini.Read(S, "KeepAwake", "1") != "0"; } set { Ini.Write(S, "KeepAwake", value ? "1" : "0"); } }

        public static HashSet<string> RegionSet(string list)
        {
            return new HashSet<string>(Preference.ParseList(list), StringComparer.OrdinalIgnoreCase);
        }

        public ScanOptions ScanOptions() { return new ScanOptions { OneGamePerTitle = OneGamePerTitle, RegionPriority = Regions, Exclude = Exclude, IgnoredRegions = RegionSet(IgnoredRegions), Ignore = IgnoreList(), KeepPacks = KeepPacks, Systems = SystemOverrides() }; }

        // Regions and ROM types for one system only (such as every region for a system only sold in Japan).
        // Saved under the system's DAT name, so renaming its folder keeps them. Regions are "order|left out".
        string SystemRegionsSection { get { return Section("System Region Overrides"); } }
        string SystemTypesSection { get { return Section("System ROM Type Overrides"); } }
        string Section(string name) { return IsDefault ? name : name + ": " + Collection; }

        // Early v1.2 builds called these sections [System Regions] and [System ROM Types]: move them over.
        void MoveOldOverrides()
        {
            foreach (var pair in new[] { new[] { Section("System Regions"), SystemRegionsSection }, new[] { Section("System ROM Types"), SystemTypesSection } })
            {
                var keys = Ini.Keys(pair[0]);
                if (keys.Count == 0) continue;
                var have = Ini.Keys(pair[1]);
                foreach (var k in keys)
                    if (!have.Contains(k, StringComparer.OrdinalIgnoreCase)) Ini.Write(pair[1], k, Ini.Read(pair[0], k, ""));
                Ini.Write(pair[0], null, null);   // removes the old section
            }
        }

        public Dictionary<string, SystemOverride> SystemOverrides()
        {
            MoveOldOverrides();
            var all = new Dictionary<string, SystemOverride>(StringComparer.OrdinalIgnoreCase);
            Func<string, SystemOverride> get = k => { SystemOverride o; if (!all.TryGetValue(k, out o)) all[k] = o = new SystemOverride(); return o; };
            foreach (var k in Ini.Keys(SystemRegionsSection))
            {
                var parts = Ini.Read(SystemRegionsSection, k, "").Split('|');
                var o = get(k);
                o.RegionPriority = parts[0];
                o.IgnoredRegions = RegionSet(parts.Length > 1 ? parts[1] : "");
            }
            foreach (var k in Ini.Keys(SystemTypesSection))
                get(k).Exclude = GameTypes.Parse(Ini.Read(SystemTypesSection, k, ""));
            return all;
        }

        // order null: use the collection's regions again.
        public void SetSystemRegions(string datName, string order, string ignored)
        {
            Ini.Write(SystemRegionsSection, datName, order == null ? null : order + "|" + ignored);
            DropIfEmpty(SystemRegionsSection);
        }

        // exclude null: use the collection's ROM types again.
        public void SetSystemTypes(string datName, GameType? exclude)
        {
            Ini.Write(SystemTypesSection, datName, exclude.HasValue ? GameTypes.ToList(exclude.Value) : null);
            DropIfEmpty(SystemTypesSection);
        }

        // Removing the last entry leaves an empty heading behind: take that away too.
        void DropIfEmpty(string section) { if (Ini.Keys(section).Count == 0) Ini.Write(section, null, null); }

        // Folders matched to a DAT by hand (folder name = DAT name).
        public Dictionary<string, string> DatMap()
        {
            var map = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
            foreach (var k in Ini.Keys(MapSection)) map[k] = Ini.Read(MapSection, k, "");
            return map;
        }
        public void SetDatMap(string folder, string dat) { Ini.Write(MapSection, folder, dat); }

        // Files you've chosen to keep although they aren't in the DAT (such as a translation guide), per system.
        // Saved under the system's DAT name, so renaming the folder doesn't lose them. Each value is a list of
        // paths relative to the system folder, separated by "|" (which can't be in a file name).
        string IgnoreSection { get { return IsDefault ? "Ignore" : "Ignore: " + Collection; } }

        public Dictionary<string, HashSet<string>> IgnoreList()
        {
            var list = new Dictionary<string, HashSet<string>>(StringComparer.OrdinalIgnoreCase);
            foreach (var k in Ini.Keys(IgnoreSection))
                list[k] = new HashSet<string>(Ini.Read(IgnoreSection, k, "").Split(new[] { '|' }, StringSplitOptions.RemoveEmptyEntries), StringComparer.OrdinalIgnoreCase);
            return list;
        }

        public void SetIgnored(string datName, IEnumerable<string> names, bool ignore)
        {
            HashSet<string> set;
            if (!IgnoreList().TryGetValue(datName, out set)) set = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            foreach (var n in names) { if (ignore) set.Add(n); else set.Remove(n); }
            Ini.Write(IgnoreSection, datName, set.Count == 0 ? null : string.Join("|", set.OrderBy(n => n, StringComparer.OrdinalIgnoreCase)));
        }
    }
