    static class Program
    {
        [DllImport("user32.dll")] static extern bool SetProcessDPIAware();

        [STAThread]
        static int Main(string[] args)
        {
            // Allow paths longer than 260 characters (No-Intro names can be long). Must be set before any file access.
            AppContext.SetSwitch("Switch.System.IO.UseLegacyPathHandling", false);
            AppContext.SetSwitch("Switch.System.IO.BlockLongPaths", false);

            if (args.Length > 0 && args[0].Equals("/report", StringComparison.OrdinalIgnoreCase))
                return CommandLine.Run(args);

            bool isFirst;
            using (var mutex = new Mutex(true, "ROM-Check-O-MATIC-SingleInstance", out isFirst))
            {
                if (!isFirst) return 0;
                try { SetProcessDPIAware(); } catch { }
                Application.EnableVisualStyles();
                Application.SetCompatibleTextRenderingDefault(false);
                Application.Run(new MainForm());
            }
            return 0;
        }
    }

    // ROM-Check-O-MATIC.exe /report "<ROM folder>" "<report.txt>" [/dat "<DAT folder>"] [/onegame] [/regions "USA, Europe"]
    //                       [/leaveout "Beta,Proto,Demo,Unlicensed,Pirate,Aftermarket,Bios,Program"]
    //                       [/ignoreregions "Brazil, Korea"] [/collection "Redump"] [/fix] [/delete] [/addfrom "<missing ROMs folder>"]
    // Writes a report without opening a window. /fix renames, /delete permanently deletes unneeded files,
    // /addfrom adds missing games found in a folder (and removes those downloads).
    static class CommandLine
    {
        public static int Run(string[] args)
        {
            string outFile = args.Length > 2 ? args[2] : null;
            try
            {
                if (args.Length < 3) throw new ArgumentException("Usage: /report \"<ROM folder>\" \"<report file>\" [/dat \"<DAT folder>\"] [/onegame] [/regions \"...\"] [/fix] [/delete]");
                string root = args[1];
                // /collection "Redump" uses that collection's saved folders and settings.
                int ci = Array.FindIndex(args, a => a.Equals("/collection", StringComparison.OrdinalIgnoreCase));
                var settings = ci >= 0 && ci + 1 < args.Length ? new Settings(args[ci + 1]) : new Settings();
                Fixer.UseRecycleBin = settings.UseRecycleBin;
                if (settings.KeepAwake) Awake.Set(true);   // cleared when the process ends
                string datRoot = settings.DatFolder;
                var opts = settings.ScanOptions();
                bool fix = false, delete = false;
                string addFrom = null;
                for (int i = 3; i < args.Length; i++)
                {
                    string a = args[i].ToLowerInvariant();
                    if (a == "/dat" && i + 1 < args.Length) datRoot = args[++i];
                    else if (a == "/regions" && i + 1 < args.Length) opts.RegionPriority = args[++i];
                    else if (a == "/onegame") opts.OneGamePerTitle = true;
                    else if (a == "/noaftermarket") opts.Exclude |= GameType.Aftermarket;
                    else if (a == "/leaveout" && i + 1 < args.Length) opts.Exclude = GameTypes.Parse(args[++i]);
                    else if (a == "/ignoreregions" && i + 1 < args.Length) opts.IgnoredRegions = Settings.RegionSet(args[++i]);
                    else if (a == "/fix") fix = true;
                    else if (a == "/delete") delete = true;
                    else if (a == "/collection") i++;
                    else if (a == "/addfrom" && i + 1 < args.Length) addFrom = args[++i];
                }
                var ct = CancellationToken.None;
                var index = DatIndex.Build(datRoot, ct);
                opts.Cues = CueIndex.Build(root, datRoot, settings.CueFolder);
                var manual = settings.DatMap();
                var folders = MainForm.SystemFolders(root, index, manual);
                var results = folders.Select(f => Scanner.ScanSystem(f, index, manual, opts, null, ct)).ToList();
                var log = new StringBuilder();
                if (delete || fix)
                {
                    if (delete)
                    {
                        foreach (var line in Actions.DeleteAll(results.SelectMany(s => s.Files).Where(f => f.IsUnneeded && f.CanChange).ToList(), null, ct))
                            log.AppendLine(line);
                        folders = MainForm.SystemFolders(root, index, manual);
                        results = folders.Select(f => Scanner.ScanSystem(f, index, manual, opts, null, ct)).ToList();
                    }
                    if (fix)
                        foreach (var line in Actions.FixAll(results.SelectMany(s => s.Files).Where(f => f.IsFixable && f.CanChange).ToList(), null, ct))
                            log.AppendLine(line);
                    folders = MainForm.SystemFolders(root, index, manual);   // unpacked TOSEC packs become folders
                    results = folders.Select(f => Scanner.ScanSystem(f, index, manual, opts, null, ct)).ToList();
                }
                if (addFrom != null)
                {
                    var plan = Intake.Plan(addFrom, results, index, null, ct);
                    foreach (var f in plan.Where(f => !f.Matches.Any(m => m.Error == null))) log.AppendLine("Left in place: " + f.Name + " (" + f.Outcome + ")");
                    foreach (var line in Intake.Apply(plan, settings.RemoveDownloads, null, ct)) log.AppendLine(line);
                    results = folders.Select(f => Scanner.ScanSystem(f, index, manual, opts, null, ct)).ToList();
                }
                File.WriteAllText(outFile, (log.Length > 0 ? "Actions:\r\n" + log + "\r\n" : "") + Report.Build(results, true), Encoding.UTF8);
                return 0;
            }
            catch (Exception ex)
            {
                try { if (outFile != null) File.WriteAllText(outFile, "Error: " + ex, Encoding.UTF8); } catch { }
                return 1;
            }
        }
    }

    // Stops Windows going to sleep while a long job runs. The screen can still turn off.
    static class Awake
    {
        [DllImport("kernel32.dll")] static extern uint SetThreadExecutionState(uint flags);
        const uint ES_CONTINUOUS = 0x80000000, ES_SYSTEM_REQUIRED = 0x00000001;

        // Call from the same thread each time (the window's thread): Windows ties the request to that thread.
        public static void Set(bool on)
        {
            try { SetThreadExecutionState(on ? ES_CONTINUOUS | ES_SYSTEM_REQUIRED : ES_CONTINUOUS); } catch { }
        }
    }

    static class Actions
    {
        // Renames every file in the list. Files whose new name is taken by another file in the list
        // are retried after that file has moved out of the way. Returns one line per file.
        public static List<string> FixAll(List<FileResult> files, Action<int, int> progress, CancellationToken ct)
        {
            var lines = new List<string>();
            // Games inside TOSEC packs: each pack is rewritten (or unpacked) once, for all its games together.
            foreach (var g in files.Where(f => f.InPack).GroupBy(f => f.System))
            {
                ct.ThrowIfCancellationRequested();
                if (g.Key.KeepPack) lines.AddRange(Packs.Rewrite(g.Key, g.ToList(), new FileResult[0], progress, ct));
                else lines.AddRange(Packs.Unpack(g.Key, progress, ct));
            }
            files = files.Where(f => !f.InPack).ToList();
            var todo = files;
            int done = 0;
            for (int pass = 0; pass < 4 && todo.Count > 0; pass++)
            {
                var retry = new List<FileResult>();
                foreach (var f in todo)
                {
                    ct.ThrowIfCancellationRequested();
                    string err = Fixer.Fix(f);
                    if (err == null) { lines.Add("Renamed " + f.Name + " -> " + f.TargetName); done++; }
                    else if (err.Contains("already exists") && pass < 3) { retry.Add(f); continue; }
                    else { lines.Add("COULDN'T RENAME " + f.Name + ": " + err); done++; }
                    if (progress != null) progress(done, files.Count);
                }
                if (retry.Count == todo.Count) // nothing moved, so retrying won't help
                {
                    foreach (var f in retry) lines.Add("COULDN'T RENAME " + f.Name + ": " + Fixer.Fix(f));
                    break;
                }
                todo = retry;
            }
            return lines;
        }

        // Deletes every file in the list (permanently). Games inside a TOSEC pack are taken out of it, with the
        // pack rewritten once for all of them. Returns one line per file (or per pack).
        public static List<string> DeleteAll(List<FileResult> files, Action<int, int> progress, CancellationToken ct)
        {
            var lines = new List<string>();
            foreach (var g in files.Where(f => f.InPack).GroupBy(f => f.System))
            {
                ct.ThrowIfCancellationRequested();
                lines.AddRange(Packs.Rewrite(g.Key, new FileResult[0], g.ToList(), progress, ct));
            }
            var rest = files.Where(f => !f.InPack).ToList();
            int done = 0;
            foreach (var f in rest)
            {
                ct.ThrowIfCancellationRequested();
                string err = Fixer.Delete(f);
                bool inside = f.Kind == FileKind.ExtraInside;
                lines.Add(err == null ? (inside ? "Took the extra files out of " : "Deleted ") + f.Name
                                      : (inside ? "COULDN'T TAKE THE EXTRA FILES OUT OF " : "COULDN'T DELETE ") + f.Name + ": " + err);
                if (progress != null) progress(++done, rest.Count);
            }
            return lines;
        }
    }

